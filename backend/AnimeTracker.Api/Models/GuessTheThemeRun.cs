namespace AnimeTracker.Api.Models;

/// <summary>Where a Guess the Opening/Ending game is within a song: the clip is
/// being listened to, or the answer is on show. Stored by name.</summary>
public enum GuessTheThemePhase
{
    Listening,
    Revealed,
}

/// <summary>The one Guess the Opening/Ending game in progress, and nothing else
/// about it (add-anime-themes-and-guess-the-theme design.md D7). Deleted when
/// the game ends, however it ends, so "in progress" is simply "a row exists" and
/// no count of songs guessed, best result or history lives anywhere: the game
/// keeps no score. The settings are the ones the game started with, so a later
/// Hide NSFW change doesn't alter a game under way. The song being played lives
/// on its <see cref="GuessTheThemeRound"/>, copied from the catalogue, so a
/// catalogue refresh mid-game can't change or remove it.</summary>
public class GuessTheThemeRun
{
    public int Id { get; set; }

    /// <summary>Bumped by every move. The concurrency token: a double press, or a
    /// move from a tab behind the game, can't be applied twice, and the move
    /// number the client sends is how a stale one is told apart.</summary>
    public int Moves { get; set; }

    /// <summary>The song, from 1. It identifies the round being played, for the
    /// clip's address, and is shown nowhere: the game keeps no score.</summary>
    public int Round { get; set; } = 1;

    /// <summary>The position on the ladder of lengths, 0 to 5
    /// (<c>GuessTheThemeLadder</c>).</summary>
    public int Step { get; set; }

    public GuessTheThemePhase Phase { get; set; }

    /// <summary>The anime guessed wrong this round, so none is offered twice. No
    /// foreign key (an array can't have one): a wrong guess of an anime the app
    /// hasn't stored keeps its id here and is never fetched.</summary>
    public List<int> RoundGuesses { get; set; } = [];

    /// <summary>The song ids already played, which is what stops a song repeating
    /// in a game, even through another anime that uses it. Kept on the run so
    /// deleting it leaves nothing behind.</summary>
    public List<int> PlayedSongIds { get; set; } = [];

    public int? YearFrom { get; set; }
    public int? YearTo { get; set; }

    /// <summary>Null means every type.</summary>
    public List<string>? MediaTypes { get; set; }

    public GameListScope ListScope { get; set; }
    public bool HideHentai { get; set; }
    public GameThemeChoice Themes { get; set; }

    /// <summary>The songs this game has drawn: the one being played and, during a reveal, the
    /// next. Never loaded with the run; the navigation exists so a run and its first song
    /// can be saved together, the run's id being generated by the database.</summary>
    public List<GuessTheThemeRound> Rounds { get; set; } = [];
}
